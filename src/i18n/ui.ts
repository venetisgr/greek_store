export type UiKey = keyof (typeof ui)['en'];

export function t(locale: Locale, key: UiKey): string {
  return ui[locale][key];
}

/** Path prefix for a locale: '' for en, '/el' for el. */
export function prefix(locale: Locale): string {
  return locale === 'en' ? '' : '/el';
}

/** The same path in the other locale, for the language switch. */
export function altPath(locale: Locale, path: string): string {
  if (locale === 'en') return path === '/' ? '/el/' : `/el${path}`;
  const stripped = path.replace(/^\/el/, '');
  return stripped === '' || stripped === '/' ? '/' : stripped;
}
